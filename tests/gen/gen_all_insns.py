def n(x):   # decimal, least significant digit first
    s = str(x); return "".join(D[int(c)] for c in reversed(s))
def h(x):   # hex
    HEX = D + "أبجدهو"; s = format(x, "x"); return "٠س" + "".join(HEX[int(c,16)] for c in reversed(s))
def b(x):
    s = format(x, "b"); return "٠ث" + "".join(D[int(c)] for c in reversed(s))
def reg(prefix, k): return prefix + n(k)

