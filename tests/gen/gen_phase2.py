# Generates tests/asm/أشباه_التعليمات.تجميع: every pseudo-instruction, the M
# extension, pc-relative relocations and many حمل_قيمة values (edge cases plus
# random ones), with numbers converted to file order.
# Usage: python3 tests/gen/gen_phase2.py "tests/asm/أشباه_التعليمات.تجميع"
import random
import sys

D = "٠١٢٣٤٥٦٧٨٩"
HEX = D + "أبجدهو"


def n(x):
    sign = "-" if x < 0 else ""
    return sign + "".join(D[int(c)] for c in reversed(str(abs(x))))


def h(x):
    return "٠س" + "".join(HEX[int(c, 16)] for c in reversed(format(x, "x")))


L = []
a = L.append
a("# أشباه التعليمات وامتداد الضرب والنقل النسبي")
a(".شفرة")
a(".عام دالة")
a("دالة:")
M = ["ضرب", "ضرب_عالي", "ضرب_عالي_بإشارة_وبلا_إشارة", "ضرب_عالي_بلا_إشارة", "قسمة",
     "قسمة_بلا_إشارة", "باقي", "باقي_بلا_إشارة", "ضرب_كلمة", "قسمة_كلمة",
     "قسمة_بلا_إشارة_كلمة", "باقي_كلمة", "باقي_بلا_إشارة_كلمة"]
for i, m in enumerate(M):
    a(f"    {m} وسيط{n(i % 8)}، مؤقت{n(i % 7)}، محفوظ{n(i % 12)}")

edges = [0, 1, -1, 2047, -2048, 2048, -2049, 4095, 4096, 0x7FF, 0x800, 0xFFF, 0x1000,
         0x12345, 0x7FFFF7FF, 0x7FFFF800, 0x7FFFFFFF, -0x80000000, -0x7FFFF801,
         0x80000000, 0xFFFFFFFF, 0x100000000, 0x100000001, 0x7FFFFFFFFFFFFFFF,
         -0x8000000000000000, 0x123456789ABCDEF0, -1234567890123, 0xFFFFFFFF00000000,
         0x8000000000000001, 0x00FF00FF00FF00FF, 1 << 40, (1 << 63) - (1 << 12)]
rng = random.Random(2026)
vals = list(edges)
for bits in range(1, 64):
    for _ in range(3):
        v = rng.getrandbits(bits)
        vals.append(v if rng.random() < 0.5 else -v)
for i, v in enumerate(vals):
    if v >= 1 << 63:
        v -= 1 << 64
    lit = n(v) if (i % 3 or v < 0) else h(v)
    a(f"    حمل_قيمة وسيط{n(i % 8)}، {lit}")
a(f"    حمل_قيمة مؤقت{n(0)}، ) {n(3)} + {n(4)} ( * {n(1000)}")

a("    حمل_عنوان وسيط٠، متغير")
a(f"    حمل_عنوان وسيط١، متغير + {n(8)}")
a("    حمل_عنوان وسيط٢، خارجي")
a(f"    حمل_عنوان وسيط٣، ) خارجي - {n(16)} (")
a("    حمل_عنوان وسيط٤، دالة")
a("    حمل_عنوان وسيط٥، محلي")
a("    نسخ وسيط٠، محفوظ١١")
a("    نفي مؤقت٦، صفر")
a("    سالب سجل١٣، وسيط٧")
a("    لا_عملية")
a("محلي:")
a("    قفز محلي")
a(f"    قفز {n(1)}ق")
a("    قفز خارجي")
a("    قفز_بسجل وسيط٠")
a("    استدعاء دالة")
a("    استدعاء محلي")
a("    استدعاء خارجي")
a(f"    استدعاء خارجي + {n(4)}")
a("    استدعاء_أخير خارجي")
a("    استدعاء_أخير محلي")
a("    عودة")
for m in ["تفرع_إذا_صفر", "تفرع_إذا_ليس_صفرا"]:
    a(f"    {m} وسيط٠، محلي")
    a(f"    {m} مؤقت٦، {n(1)}ق")
for m in ["تفرع_إذا_أكبر", "تفرع_إذا_أصغر_أو_يساوي", "تفرع_إذا_أكبر_بلا_إشارة",
          "تفرع_إذا_أصغر_أو_يساوي_بلا_إشارة"]:
    a(f"    {m} وسيط٠، وسيط١، محلي")
    a(f"    {m} سجل{n(31)}، صفر، {n(1)}ق")
a(f"{n(1)}:")
a("    جمع_علوي_للعداد وسيط٠، عالي_نسبي:متغير")
a("    جمع_فوري وسيط٠، وسيط٠، أدنى_نسبي:١م")
a(f"{n(2)}: جمع_علوي_للعداد وسيط١، عالي_نسبي:) خارجي + {n(12)} (")
a(f"    حمل_كلمة_مزدوجة وسيط٢، وسيط١ + أدنى_نسبي:{n(2)}م")
a(f"    خزن_كلمة_مزدوجة وسيط٢، وسيط١ + أدنى_نسبي:{n(2)}م")
a(f"    قفز_وربط_بسجل عنوان_العودة، وسيط١ + أدنى_نسبي:{n(2)}م")
a("    عودة")
a(".بيانات")
a(f"متغير: .كلمة_مزدوجة {n(0)}، {n(0)}")
open(sys.argv[1], "w", encoding="utf-8").write("\n".join(L) + "\n")
