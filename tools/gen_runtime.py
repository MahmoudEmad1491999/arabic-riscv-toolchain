#!/usr/bin/env python3
"""Writes lib/runtime/تشغيل.تجميع, the runtime of غرة programs, in Arabic
assembly. Numbers are converted to file order here, and the stop messages
are stored reversed (display order) so a plain left-to-right terminal shows
them correctly (assumption A18).

Provides: _بداية (builds the argument slice, calls رئيسية, exits with its
result), _غرة_انسخ (memory copy used by the compiler), _غرة_اكتب (write),
_غرة_اخرج (exit), and the run-time stops _غرة_خارج_الحدود,
_غرة_تحويل_فاشل, _غرة_فيض (message on stderr, exit code 101).
Usage: tools/gen_runtime.py
"""
import os

D = "٠١٢٣٤٥٦٧٨٩"
MSGS = {
    "رسالة_الحدود": "خطأ: فهرس خارج الحدود",
    "رسالة_التحويل": "خطأ: قيمة لا تتسع في النوع",
    "رسالة_الفيض": "خطأ: فيض في عملية حسابية",
}
STOPS = [("_غرة_خارج_الحدود", "رسالة_الحدود"), ("_غرة_تحويل_فاشل", "رسالة_التحويل"),
         ("_غرة_فيض", "رسالة_الفيض")]


def n(x):
    return "".join(D[int(c)] for c in reversed(str(x)))


def disp(s):
    return s[::-1]


def main():
    L = []
    a = L.append
    a("# مكتبة التشغيل لغرة: نقطة البداية والنسخ والكتابة والتوقف")
    a("# رسائل التوقف مخزنة معكوسة لتظهر صحيحة على طرفية بلا اتجاه ثنائي")
    a(".شفرة")
    a(".عام _بداية، _غرة_انسخ، _غرة_اكتب، _غرة_اخرج، " + "، ".join(s for s, _ in STOPS))
    a("")
    a("# _بداية: يبني شريحة الوسائط ويستدعي رئيسية ثم يخرج بقيمتها")
    a("_بداية:")
    a("    حمل_كلمة_مزدوجة محفوظ١، مؤشر_المكدس")
    a(f"    جمع_فوري محفوظ٢، مؤشر_المكدس، {n(8)}")
    a(f"    رفع_فوري مؤقت٠، محفوظ١، {n(4)}")
    a("    طرح مؤشر_المكدس، مؤشر_المكدس، مؤقت٠")
    a("    نسخ محفوظ٣، مؤشر_المكدس")
    a(f"    حمل_قيمة مؤقت١، {n(0)}")
    a(f"{n(1)}:")
    a(f"    تفرع_إذا_أكبر_أو_يساوي_بلا_إشارة مؤقت١، محفوظ١، {n(2)}ق")
    a(f"    رفع_فوري مؤقت٢، مؤقت١، {n(3)}")
    a("    جمع مؤقت٢، محفوظ٢، مؤقت٢")
    a("    حمل_كلمة_مزدوجة مؤقت٢، مؤقت٢")
    a("    نسخ مؤقت٣، مؤقت٢")
    a(f"{n(3)}:")
    a("    حمل_بايت_بلا_إشارة مؤقت٤، مؤقت٣")
    a(f"    تفرع_إذا_صفر مؤقت٤، {n(4)}ق")
    a(f"    جمع_فوري مؤقت٣، مؤقت٣، {n(1)}")
    a(f"    قفز {n(3)}م")
    a(f"{n(4)}:")
    a("    طرح مؤقت٣، مؤقت٣، مؤقت٢")
    a(f"    رفع_فوري مؤقت٤، مؤقت١، {n(4)}")
    a("    جمع مؤقت٤، محفوظ٣، مؤقت٤")
    a("    خزن_كلمة_مزدوجة مؤقت٢، مؤقت٤")
    a(f"    خزن_كلمة_مزدوجة مؤقت٣، مؤقت٤ + {n(8)}")
    a(f"    جمع_فوري مؤقت١، مؤقت١، {n(1)}")
    a(f"    قفز {n(1)}م")
    a(f"{n(2)}:")
    a("    نسخ وسيط٠، محفوظ٣")
    a("    نسخ وسيط١، محفوظ١")
    a("    استدعاء رئيسية")
    a(f"    حمل_قيمة وسيط٧، {n(93)}")
    a("    نداء_البيئة")
    a("")
    a("# _غرة_انسخ: ينسخ وسيط٢ بايتا من وسيط١ إلى وسيط٠")
    a("_غرة_انسخ:")
    a(f"    تفرع_إذا_صفر وسيط٢، {n(2)}ق")
    a(f"{n(1)}:")
    a("    حمل_بايت_بلا_إشارة مؤقت٠، وسيط١")
    a("    خزن_بايت مؤقت٠، وسيط٠")
    a(f"    جمع_فوري وسيط٠، وسيط٠، {n(1)}")
    a(f"    جمع_فوري وسيط١، وسيط١، {n(1)}")
    a(f"    جمع_فوري وسيط٢، وسيط٢، -{n(1)}")
    a(f"    تفرع_إذا_ليس_صفرا وسيط٢، {n(1)}م")
    a(f"{n(2)}:")
    a("    عودة")
    a("")
    a("# _غرة_اكتب: الملف في وسيط٠، الشريحة في وسيط١ و وسيط٢")
    a("_غرة_اكتب:")
    a(f"    حمل_قيمة وسيط٧، {n(64)}")
    a("    نداء_البيئة")
    a("    عودة")
    a("")
    a("_غرة_اخرج:")
    a(f"    حمل_قيمة وسيط٧، {n(93)}")
    a("    نداء_البيئة")
    a("")
    for sym, msg in STOPS:
        a(f"{sym}:")
        a(f"    حمل_قيمة وسيط٠، {n(2)}")
        a(f"    حمل_عنوان وسيط١، {msg}")
        a(f"    حمل_قيمة وسيط٢، {n(len((disp(MSGS[msg]) + chr(10)).encode()))}")
        a(f"    حمل_قيمة وسيط٧، {n(64)}")
        a("    نداء_البيئة")
        a(f"    حمل_قيمة وسيط٠، {n(101)}")
        a(f"    حمل_قيمة وسيط٧، {n(93)}")
        a("    نداء_البيئة")
        a("")
    a(".بيانات_للقراءة")
    for name, text in MSGS.items():
        a(f"{name}: .سلسلة \"{disp(text)}\\س\"")
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
    with open(os.path.join(root, "lib", "runtime", "تشغيل.تجميع"), "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
